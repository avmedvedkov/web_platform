#!/bin/bash

# run.sh - Скрипт запуска приложения Автоматического сортировщика

set -e  # Выход при ошибке

# Определяем директорию скрипта
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$SCRIPT_DIR"

# Цвета для вывода
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
RED='\033[0;31m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

echo -e "${BLUE}=========================================${NC}"
echo -e "${BLUE} МНПЦЛИ · Энтеробиоз - Запуск приложения ${NC}"
echo -e "${BLUE}=========================================${NC}"

# Проверяем виртуальную среду
if [ ! -d "venv" ]; then
    echo -e "${YELLOW}Виртуальная среда не найдена. Создание...${NC}"
    
    # Создаем виртуальную среду
    echo -e "${BLUE}Создание виртуальной среды...${NC}"
    python3.13 -m venv venv
    
    # Активируем виртуальную среду
    echo -e "${BLUE}Активация виртуальной среды...${NC}"
    source venv/bin/activate
    
    # Обновляем pip
    echo -e "${BLUE}Обновление pip...${NC}"
    pip install --upgrade pip
    
    # Устанавливаем зависимости
    echo -e "${BLUE}Установка зависимостей...${NC}"
    pip install -r requirements.txt
    
    echo -e "${GREEN}✓ Виртуальная среда создана и зависимости установлены${NC}"
else
    # Активируем существующую виртуальную среду
    echo -e "${BLUE}Активация виртуальной среды...${NC}"
    source venv/bin/activate
    
    # Проверяем обновления
    echo -e "${BLUE}Проверка обновлений зависимостей...${NC}"
    if [ -f "requirements.txt" ]; then
        pip install -r requirements.txt --quiet
        echo -e "${GREEN}✓ Зависимости актуальны${NC}"
    fi
fi





# Информация о системе
echo -e "${BLUE}Информация о системе:${NC}"
echo "  Python: $(python3 --version)"
echo "  ОС: $(uname -s) $(uname -m)"
echo "  Директория: $(pwd)"

# Запуск приложения
echo -e "${BLUE}=========================================${NC}"
echo -e "${GREEN}Запуск приложения МНПЦЛИ · Энтеробиоз...${NC}"
echo -e "${BLUE}=========================================${NC}"

# Запуск основного приложения
python3 main.py

# Сообщение при завершении
echo -e "${BLUE}=========================================${NC}"
echo -e "${GREEN}Приложение завершено.${NC}"
echo -e "Логи сохранены в папке logs/"
echo -e "${BLUE}=========================================${NC}"